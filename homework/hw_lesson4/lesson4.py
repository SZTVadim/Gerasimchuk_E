# ============================================
# ЗАДАНИЕ 7: Проверка типа символов
# ============================================
# Проверьте следующие строки:
# 1. "Hello123" - содержит только буквы и цифры?
# 2. "12345" - содержит только цифры?
# 3. "Hello" - содержит только буквы?
# 4. "   " - содержит только пробелы?

print("Hello123".isalnum())
print("12345".isdigit())
print("Hello".isalpha())
print("   ".isspace())

