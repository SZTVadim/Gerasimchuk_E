# ЗАДАНИЕ 2: Преобразование регистра строк
# ============================================
# Дана строка: "python PROGRAMMING"
# 1. Переведите всю строку в нижний регистр
# 2. Переведите всю строку в верхний регистр
# 3. Сделайте первую букву заглавной
# 4. Сделайте каждое слово с заглавной буквы

str_ex_2 = "python PROGRAMMING"
