# ============================================
# ЗАДАНИЕ 3: Удаление пробелов
# ============================================
# Дана строка с пробелами: "  Hello World  "
# 1. Удалите пробелы с обоих концов
# 2. Удалите пробелы только слева
# 3. Удалите пробелы только справа

str_ex_3 = "  Hello World  "
print(str_ex_3.strip(), str_ex_3.lstrip(), str_ex_3.rstrip(), sep="\n")

# ============================================
# ЗАДАНИЕ 4: Разделение и объединение строк
# ============================================
# Дана строка: "яблоко,банан,апельсин,груша"
# 1. Разделите строку по запятой и сохраните в список
# 2. Объедините элементы списка обратно в строку, но используя разделитель " | "

str_ex_4 = "яблоко,банан,апельсин,груша"
list_ex_4 = str_ex_4.split(",")
str_ex_4_2 = "|".join(list_ex_4)
print(str_ex_4, list_ex_4, str_ex_4_2, sep="\n")

